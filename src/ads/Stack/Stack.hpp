#pragma once
#include <iostream>
#include <string>

#include "../Node/Node.hpp"

class Stack {
 private:
  Node* top_;
  int size_;

 public:
  // ============================================================================
  // КОНСТРУКТОР
  // ============================================================================
  Stack() : top_(nullptr), size_(0) {}
  // ============================================================================
  // ДЕСТРУКТОР
  // ============================================================================
  ~Stack() {
    while (top_ != nullptr) {
      pop();  // используем существующий метод
    }
  }
  // ============================================================================
  // ЗАПРЕТ КОПИРОВАНИЯ И ПРИСВАИВАНИЯ
  // ============================================================================
  Stack(const Stack&) = delete;
  Stack& operator=(const Stack&) = delete;

  // ============================================================================
  // STK1 Добавление элемента: DPUSH value
  // ============================================================================
  void push(const std::string& value);

  // ============================================================================
  // STK2 Удаление элемента: DPOP
  // ============================================================================
  void pop();

  // ============================================================================
  // STK3 Печать стека: PRINT
  // ============================================================================
  void print() const;

  // ============================================================================
  // STK4 Получение вершины стека: TOP
  // =================
  // ===========================================================
  std::string top() const;

  // ============================================================================
  // STK5 Проверка пустоты стека
  // =================
  // ===========================================================
  bool isEmpty() const;

  // ============================================================================
  // STK6 СОХРАНЕНИЕ В ФАЙЛ
  // =================
  // ===========================================================
  void saveToFile(const std::string& filename) const;

  // ============================================================================
  // STK7 ЗАГРУЗКА ИЗ ФАЙЛА
  // ============================================================================
  void loadFromFile(const std::string& filename);
};