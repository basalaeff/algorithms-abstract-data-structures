#include "Set.hpp"

// ============================================================================
// HASH FUNCTION
// ============================================================================
// Преобразует строку в индекс hash table.
//
// Алгоритм:
// 1) Берём каждый символ строки.
// 2) Переводим символ в число.
// 3) Накапливаем hash.
// 4) Ограничиваем результат размером таблицы.
//
// Сложность: O(n)
// ============================================================================

int Set::hash(const std::string& value) const {
  unsigned long hashValue = 0;

  for (char ch : value) {
    hashValue = hashValue * 31 + static_cast<unsigned char>(ch);
  }

  return hashValue % TABLE_SIZE;
}