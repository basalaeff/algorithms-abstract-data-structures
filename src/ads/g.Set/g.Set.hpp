#include "../Node/Node.hpp"

// ============================================================================
// SET
// ============================================================================
// Реализация АТД "Множество" через hash table.
//
// Все основные операции:
// - добавление
// - удаление
// - проверка наличия
//
// выполняются за O(1) в среднем.
//
// Для разрешения коллизий используется linked list.
// ============================================================================

class Set {
 private:
  // Размер hash table
  // Простое число уменьшает количество коллизий
  static const int TABLE_SIZE = 101;

  // Массив указателей на списки
  Node* table_[TABLE_SIZE];

  // ==========================================================================
  // HASH FUNCTION
  // ==========================================================================
  // Преобразует строку в индекс массива.
  // Возвращает число от 0 до TABLE_SIZE - 1.
  // ==========================================================================
  int hash(const std::string& value) const;

 public:
  // ==========================================================================
  // КОНСТРУКТОР
  // ==========================================================================
  // Инициализирует всю hash table nullptr.
  // ==========================================================================
  Set();

  // ==========================================================================
  // ДЕСТРУКТОР
  // ==========================================================================
  // Освобождает всю выделенную память.
  // ==========================================================================
  ~Set();

  // ==========================================================================
  // SETADD
  // ==========================================================================
  // Добавляет элемент в множество.
  // Если элемент уже существует — ничего не делает.
  // Сложность: O(1)
  // ==========================================================================
  void add(const std::string& value);

  // ==========================================================================
  // ЗАГРУЗКА ИЗ ФАЙЛА
  // ==========================================================================
  // Загружает данные из файла.
  // Каждая строка файла становится элементом множества.
  // ==========================================================================
  void loadFromFile(const std::string& filename);

  // ==========================================================================
  // СОХРАНЕНИЕ В ФАЙЛ
  // ==========================================================================
  // Сохраняет все элементы множества в файл.
  // ==========================================================================
  void saveToFile(const std::string& filename) const;
};