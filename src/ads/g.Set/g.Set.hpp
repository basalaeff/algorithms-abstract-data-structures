#include "../Node/Node.hpp"

// ============================================================================
// SET
// ============================================================================
// Реализация АТД "Множество" через hash table.
//
// Все основные операции:
// - добавление
// - удаление
// - проверка наличия
//
// выполняются за O(1) в среднем.
//
// Для разрешения коллизий используется linked list.
// ============================================================================

class Set {
 private:
  // Размер hash table
  // Простое число уменьшает количество коллизий
  static const int TABLE_SIZE = 101;

  // Массив указателей на списки
  Node* table_[TABLE_SIZE];

  // ==========================================================================
  // HASH FUNCTION
  // ==========================================================================
  // Преобразует строку в индекс массива.
  // Возвращает число от 0 до TABLE_SIZE - 1.
  // ==========================================================================
  int hash(const std::string& value) const;
};