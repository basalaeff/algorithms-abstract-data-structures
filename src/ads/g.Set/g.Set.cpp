#include "g.Set.hpp"

// ============================================================================
// КОНСТРУКТОР
// ============================================================================
// Инициализирует всю hash table значениями nullptr.
// ============================================================================

Set::Set() {
  for (int i = 0; i < TABLE_SIZE; i++) {
    table_[i] = nullptr;
  }
}

// ============================================================================
// ДЕСТРУКТОР
// ============================================================================
// Полностью очищает hash table и освобождает память.
// ============================================================================

Set::~Set() {
  for (int i = 0; i < TABLE_SIZE; i++) {
    Node* current = table_[i];

    while (current != nullptr) {
      Node* temp = current;

      current = current->next_;

      delete temp;
    }
  }
}