#include "g.Set.hpp"

// ============================================================================
// G5 КОЛИЧЕСТВО ЭЛЕМЕНТОВ ПЕРЕСЕЧЕНИЯ
// ============================================================================
// Подсчет количества общих элементов двух множеств.
//
// 1) Проходим по всем ячейкам hash table текущего множества.
// 2) Проходим по каждому linked list внутри ячейки.
// 3) Для каждого элемента проверяем наличие во втором множестве через SET_AT.
// 4) Если элемент найден во втором множестве — увеличиваем счетчик.
//
// Сложность: O(n), где n — количество элементов текущего множества.
// ============================================================================

int Set::intersectionCount(const Set& other) const {
  int count = 0;

  for (int i = 0; i < TABLE_SIZE; i++) {
    Node* current = table_[i];

    while (current != nullptr) {
      if (other.at(current->data_)) {
        count++;
      }

      current = current->next_;
    }
  }

  return count;
}
