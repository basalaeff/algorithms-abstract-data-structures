#include "d.Stack.hpp"

// ============================================================================
// D4 Получение вершины стека: TOP
// ============================================================================
// 1) Если стек пуст — выбрасывается исключение.
// 2) Возвращается значение вершины стека.
// 3) Элемент НЕ удаляется.
//
// Сложность: O(1)

std::string Stack::top() const {
  if (top_ == nullptr) {
    throw std::out_of_range("Stack is empty.");
  }

  return top_->data_;
}