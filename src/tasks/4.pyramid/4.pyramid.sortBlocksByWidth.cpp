// ============================================================================
// СОРТИРОВКА ПО ШИРИНЕ
// ============================================================================
// 1) Строим максимальную пирамиду по ширине.
// 2) Самый широкий блок оказывается в начале массива.
// 3) Меняем его с последним элементом текущей неотсортированной части.
// 4) Уменьшаем размер пирамиды и восстанавливаем ее.
//
// После завершения Array отсортирован по возрастанию ширины.
// Сложность: O(N log N). Дополнительная память: O(1).
// ============================================================================

void sortBlocksByWidth(Array& blocks) {
  int blocksCount = blocks.length();

  for (int i = blocksCount / 2 - 1; i >= 0; i--) {
    heapify(blocks, blocksCount, i);
  }

  for (int i = blocksCount - 1; i > 0; i--) {
    swapBlocks(blocks, 0, i);
    heapify(blocks, i, 0);
  }
}
