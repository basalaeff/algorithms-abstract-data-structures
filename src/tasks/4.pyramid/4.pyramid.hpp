#pragma once

#include <iosfwd>
#include <string>

#include "../../ads/a.Array/a.Array.hpp"

// ============================================================================
// PYRAMID
// ============================================================================
// Задача "Пирамида".
//
// Блок можно поставить на другой блок только если ширина верхнего блока строго
// меньше ширины нижнего. Блоки нельзя поворачивать.
//
// Так как высота не влияет на возможность установки, а все высоты
// положительные, для каждой ширины нужно выбрать один самый высокий блок. Блоки
// одинаковой ширины вместе использовать нельзя.
// ============================================================================

// ============================================================================
// ЧТЕНИЕ КОЛИЧЕСТВА БЛОКОВ
// ============================================================================
// Читает N и проверяет ограничение 1 <= N <= 100000.
// ============================================================================
int readBlocksCount(std::istream& input);

// ============================================================================
// ЧТЕНИЕ БЛОКОВ
// ============================================================================
// Читает пары "ширина высота" и сохраняет их в Array строками формата
// "width height". Используются только существующие методы Array.
// ============================================================================
void readBlocks(std::istream& input, Array& blocks, int blocksCount);

// ============================================================================
// ПОЛУЧЕНИЕ ШИРИНЫ БЛОКА
// ============================================================================
// Извлекает ширину из строки блока формата "width height".
// ============================================================================
long long getBlockWidth(const std::string& block);

// ============================================================================
// ПОЛУЧЕНИЕ ВЫСОТЫ БЛОКА
// ============================================================================
// Извлекает высоту из строки блока формата "width height".
// ============================================================================
long long getBlockHeight(const std::string& block);

// ============================================================================
// ОБМЕН БЛОКОВ
// ============================================================================
// Меняет местами два элемента Array через get и replaceByIndex.
// ============================================================================
void swapBlocks(Array& blocks, int firstIndex, int secondIndex);

// ============================================================================
// ВОССТАНОВЛЕНИЕ ПИРАМИДЫ
// ============================================================================
// Восстанавливает свойство максимальной пирамиды для участка массива.
// ============================================================================
void heapify(Array& blocks, int heapSize, int rootIndex);

// ============================================================================
// СОРТИРОВКА ПО ШИРИНЕ
// ============================================================================
// Сортирует блоки по возрастанию ширины с помощью пирамидальной сортировки.
// ============================================================================
void sortBlocksByWidth(Array& blocks);

// ============================================================================
// ВЫЧИСЛЕНИЕ МАКСИМАЛЬНОЙ ВЫСОТЫ
// ============================================================================
// Сортирует блоки по ширине, затем для каждой группы одинаковой ширины берет
// максимальную высоту и добавляет ее к ответу.
// ============================================================================
long long calculateMaxPyramidHeight(Array& blocks);

// ============================================================================
// ЗАПУСК
// ============================================================================
// Выполняет полный сценарий: чтение входных данных и вычисление ответа.
// ============================================================================
long long runPyramid(std::istream& input);
