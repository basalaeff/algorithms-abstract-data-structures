#include <stdexcept>

#include "3.mic.hpp"

// ============================================================================
// ПОИСК МАКСИМАЛЬНОГО ПЕРЕСЕЧЕНИЯ
// ============================================================================
// Находит два множества с максимальным количеством общих элементов.
//
// Алгоритм:
// 1) Проверяем, что есть минимум два множества.
// 2) Считаем пересечение первой пары начальным максимумом.
// 3) Перебираем все пары множеств.
// 4) Для каждой пары считаем количество общих элементов.
// 5) Если найдено пересечение не меньше текущего максимума,
//      -> сохраняем индексы этой пары;
//      -> обновляем максимальное количество общих элементов.
//
// Для подсчета пересечения используется метод Set::intersectionCount.
// ============================================================================

void Mic::findMaxIntersection() {
  if (setsCount_ < 2 || sets_ == nullptr) {
    // Требуется как минимум два множества.
    throw std::runtime_error("At least two sets are required.");
  }

  firstIndex_ = 0;
  secondIndex_ = 1;
  maxCommonCount_ = sets_[0].intersectionCount(sets_[1]);

  for (int i = 0; i < setsCount_; i++) {
    for (int j = i + 1; j < setsCount_; j++) {
      int commonCount = sets_[i].intersectionCount(sets_[j]);

      if (commonCount >= maxCommonCount_) {
        firstIndex_ = i;
        secondIndex_ = j;
        maxCommonCount_ = commonCount;
      }
    }
  }
}
