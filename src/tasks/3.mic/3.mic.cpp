#include "3.mic.hpp"

// ============================================================================
// КОНСТРУКТОР
// ============================================================================
// Создает пустую задачу без входных множеств.
// ============================================================================

Mic::Mic()
    : sets_(nullptr),
      outputs_(nullptr),
      setsCount_(0),
      firstIndex_(-1),
      secondIndex_(-1),
      maxCommonCount_(0) {}

// ============================================================================
// ДЕСТРУКТОР
// ============================================================================
// Освобождает память, выделенную под массивы множеств и вывода.
// ============================================================================

Mic::~Mic() { clear(); }

// ============================================================================
// ОЧИСТКА
// ============================================================================
// Очищает ранее созданные множества и сбрасывает результат.
// ============================================================================

void Mic::clear() {
  delete[] sets_;
  delete[] outputs_;

  sets_ = nullptr;
  outputs_ = nullptr;
  setsCount_ = 0;

  firstIndex_ = -1;  // индекс не задан
  secondIndex_ = -1;
  maxCommonCount_ = 0;
}
