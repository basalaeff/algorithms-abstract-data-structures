#pragma once

#include <string>

#include "../../ads/g.Set/g.Set.hpp"

// ============================================================================
// MIC
// ============================================================================
// Задача "Максимальное количество пересечений".
//
// Для каждого входного подмножества создается объект Set.
// Количество общих элементов считается через Set::intersectionCount.
// ============================================================================

class Mic {
 private:
  // Массив разобранных входных множеств.
  Set* sets_;

  // Массив строковых представлений множеств для последующего вывода.
  std::string* outputs_;

  // Количество множеств во входном запросе.
  int setsCount_;

  // Индекс первого множества в найденной паре с максимальным пересечением.
  int firstIndex_;

  // Индекс второго множества в найденной паре с максимальным пересечением.
  int secondIndex_;

  // Максимальное количество общих элементов среди всех пар множеств.
  int maxCommonCount_;

  // ==========================================================================
  // ПОДСЧЕТ МНОЖЕСТВ
  // ==========================================================================
  // Подсчитывает количество внутренних множеств во входной строке.
  // ==========================================================================
  int countSets(const std::string& query) const;

  // ==========================================================================
  // ОЧИСТКА
  // ==========================================================================
  // Очищает ранее созданные множества и сбрасывает результат.
  // ==========================================================================
  void clear();

 public:
  // ==========================================================================
  // КОНСТРУКТОР
  // ==========================================================================
  // Создает пустую задачу без входных множеств.
  // ==========================================================================
  Mic();

  // ==========================================================================
  // ДЕСТРУКТОР
  // ==========================================================================
  // Освобождает память, выделенную под массивы множеств и вывода.
  // ==========================================================================
  ~Mic();

  Mic(const Mic&) = delete;
  Mic& operator=(const Mic&) = delete;

  // ==========================================================================
  // РАЗБОР СТРОКИ
  // ==========================================================================
  // Разбирает строку запроса и создает Set для каждого входного множества.
  // ==========================================================================
  void parse(const std::string& query);

  // ==========================================================================
  // ПОИСК МАКСИМАЛЬНОГО ПЕРЕСЕЧЕНИЯ
  // ==========================================================================
  // Находит два множества с максимальным количеством общих элементов.
  // ==========================================================================
  void findMaxIntersection();

  // ==========================================================================
  // ФОРМАТИРОВАНИЕ РЕЗУЛЬТАТА
  // ==========================================================================
  // Формирует строку результата для вывода в консоль.
  // ==========================================================================
  std::string formatResult() const;
};